// :format — ANMP packet format and key derivation (no ANDP, no platform or UI dependencies).
//
//   ./gradlew :format:jvmTest :format:jsTest :format:testAndroidHostTest
//   ./gradlew :format:compileKotlinIosSimulatorArm64
//   UPDATE_VECTORS=1 ./gradlew :format:jvmTest   # rewrite ../vectors/anmp-v1.json

import org.jetbrains.kotlin.gradle.ExperimentalKotlinGradlePluginApi

plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.androidKotlinMultiplatformLibrary)
    alias(libs.plugins.kotlinSerialization)
}

val vectorsFile = rootProject.layout.projectDirectory.file("../vectors/anmp-v1.json")

// Embeds the test vectors as a Kotlin constant so that every target (also browser and iOS) can read them.
val generateVectors = tasks.register("generateVectors") {
    val source = providers.fileContents(vectorsFile).asText.orElse("")
    val out = layout.buildDirectory.dir("generated/anmpVectors/kotlin")
    inputs.property("vectors", source)
    outputs.dir(out)
    doLast {
        val text = source.get()
        val escaped = buildString {
            text.forEach { ch ->
                when (ch) {
                    '\\' -> append("\\\\")
                    '"' -> append("\\\"")
                    '$' -> append("\\$")
                    '\n' -> append("\\n")
                    '\r' -> {}
                    else -> append(ch)
                }
            }
        }
        val file = out.get().file("app/anynear/anmp/EmbeddedVectors.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package app.anynear.anmp\n\n" +
                "/** Content of vectors/anmp-v1.json at build time, empty if missing. Generated by format/build.gradle.kts. */\n" +
                "internal const val EMBEDDED_VECTORS: String = \"$escaped\"\n",
        )
    }
}

kotlin {
    jvmToolchain(21)

    jvm()

    android {
        namespace = "app.anynear.anmp.format"
        compileSdk = libs.versions.androidCompileSdk.get().toInt()
        minSdk = libs.versions.androidMinSdk.get().toInt()
        withHostTest {}
    }

    iosArm64()
    iosSimulatorArm64()
    iosX64()

    js {
        outputModuleName.set("anmp-format")
        // Long is exported as bigint.
        compilerOptions { freeCompilerArgs.add("-Xes-long-as-bigint") }
        browser {
            testTask {
                useKarma { useChromeHeadless() }
            }
        }
        // Hash chains (ADR 0051 §5a) need more than Mocha's default of 2 s under Node.
        nodejs { testTask { useMocha { timeout = "120s" } } }
        binaries.library()
        generateTypeScriptDefinitions()
    }

    @OptIn(ExperimentalKotlinGradlePluginApi::class)
    compilerOptions {
        optIn.add("kotlinx.serialization.ExperimentalSerializationApi")
        optIn.add("kotlin.js.ExperimentalJsExport")
        freeCompilerArgs.add("-Xexpect-actual-classes")
    }

    sourceSets {
        commonMain.dependencies {
            api(libs.serialization.cbor)
            implementation(libs.cryptography.core)
        }
        commonTest {
            kotlin.srcDir(generateVectors)
            dependencies {
                implementation(kotlin("test"))
                implementation(libs.coroutines.test)
                implementation(libs.serialization.json)
            }
        }
        jvmMain.dependencies {
            implementation(libs.cryptography.provider.jdk)
            implementation(libs.bouncycastle)
        }
        androidMain.dependencies {
            // Ed25519 and X25519 in the Android JDK only from API 33, so BouncyCastle as in the app.
            implementation(libs.cryptography.provider.jdk)
            implementation(libs.bouncycastle)
        }
        iosMain.dependencies {
            implementation(libs.cryptography.provider.optimal)
        }
        jsMain.dependencies {
            implementation(libs.cryptography.provider.optimal)
            implementation(libs.coroutines.core)
        }
    }
}

// Long as bigint also when linking (test executables).
tasks.withType<org.jetbrains.kotlin.gradle.targets.js.ir.KotlinJsIrLink>().configureEach {
    compilerOptions.freeCompilerArgs.add("-Xes-long-as-bigint")
}

tasks.withType<Test>().configureEach {
    val update = providers.environmentVariable("UPDATE_VECTORS").orElse("")
    inputs.property("updateVectors", update)
    systemProperty("anmp.vectors", vectorsFile.asFile.absolutePath)
    systemProperty("anmp.updateVectors", update.get())
}
